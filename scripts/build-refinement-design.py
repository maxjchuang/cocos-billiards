def lines(c,x,y,s,width,size=16,leading=27):
 for para in s.split('\n'):
  row=''
  for ch in para:
   if pdfmetrics.stringWidth(row+ch,'Club',size)>width and ch not in '。，；、：！？）】':
    text(c,x,y,row,size);y-=leading;row=''
   row+=ch
  if row:text(c,x,y,row,size);y-=leading
 return y

